"""Export the MetricFlow semantic layer to Lightdash.

Open-source Lightdash cannot query MetricFlow (that needs dbt Cloud's Semantic Layer API),
so MetricFlow stays the single source of truth and this script derives everything the BI
layer needs from it:

1. Pre-aggregated metric tables (models/marts/metrics/mtr_*.sql), built from the semantic
   models' measure expressions at a grain where every exported measure is additive.
   Cross-fact metrics such as net revenue (sales - returns) become possible because both
   facts land in one table.
2. Lightdash metric definitions on those tables, translated from the MetricFlow metric
   definitions: simple, derived and ratio metrics, including filtered inputs (ROAS).
3. docs/metrics_catalog.md: every metric and where it can be queried. Cumulative and
   semi-additive metrics have no faithful pre-aggregated form; they stay MetricFlow-only.

    python scripts/semantic_export.py           # write the generated files
    python scripts/semantic_export.py --check   # exit 1 if they are out of date (CI)

scripts/reconcile_metrics.py proves the exported metrics return the same numbers as `mf query`.
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
SEMANTIC_DIR = ROOT / "dbt" / "models" / "semantic"
OUT_DIR = ROOT / "dbt" / "models" / "marts" / "metrics"
CATALOG = ROOT / "docs" / "metrics_catalog.md"

GENERATED = "GENERATED by scripts/semantic_export.py from dbt/models/semantic. Do not edit by hand."

# count_distinct is not additive in general. These measures are, at every export grain below:
# a receipt or online order belongs to exactly one business date, store and channel.
ADDITIVE_DISTINCT = {"transaction_count"}


@dataclass(frozen=True)
class Source:
    semantic_model: str
    dims: dict[str, str]  # export column -> SQL expression on the fact table


@dataclass(frozen=True)
class Lookup:
    ref: str
    key: str
    columns: tuple[str, ...]


@dataclass(frozen=True)
class Export:
    name: str
    description: str
    grain: str  # "day" or "month"
    dims: tuple[str, ...]
    sources: tuple[Source, ...]
    measures: tuple[str, ...]
    metrics: tuple[str, ...] | None = None  # None: every metric whose measures are present
    lookups: tuple[Lookup, ...] = ()
    joins: tuple[tuple[str, str, str], ...] = ()  # Lightdash joins: (model, local col, remote col)

    @property
    def time_column(self) -> str:
        return "metric_date" if self.grain == "day" else "metric_month"

    @property
    def columns(self) -> list[str]:
        lookup_cols = [c for lk in self.lookups for c in lk.columns]
        return [self.time_column, *self.dims, *lookup_cols, *map(col, self.measures)]


def col(measure: str) -> str:
    """Column holding a measure in an mtr table. Prefixed, because Lightdash drops a metric
    whose name matches a column, and metrics keep their MetricFlow names (gross_sales...)."""
    return f"total_{measure}"


STORE_DIMS = {"store_key": "store_key", "channel_key": "channel_key", "country_code": "country_code"}
