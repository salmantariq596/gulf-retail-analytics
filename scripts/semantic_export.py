class Unsupported(Exception):
    """A metric that has no faithful translation onto a given export."""


# --------------------------------------------------------------------------- semantic layer
@dataclass
class SemanticLayer:
    models: dict[str, dict]
    metrics: dict[str, dict]
    measures: dict[str, tuple[str, dict]] = field(default_factory=dict)  # name -> (model, measure)

    @classmethod
    def load(cls, directory: Path = SEMANTIC_DIR) -> SemanticLayer:
        models: dict[str, dict] = {}
        metrics: dict[str, dict] = {}
        for path in sorted(directory.glob("*.yml")):
            doc = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
            models.update({m["name"]: m for m in doc.get("semantic_models", [])})
            metrics.update({m["name"]: m for m in doc.get("metrics", [])})
        layer = cls(models, metrics)
        for model in models.values():
            for measure in model.get("measures", []):
                layer.measures[measure["name"]] = (model["name"], measure)
        return layer

    def ref_name(self, model: str) -> str:
        match = re.fullmatch(r"ref\('(\w+)'\)", self.models[model]["model"])
        if not match:
            raise ValueError(f"semantic model {model}: unsupported model reference")
        return match.group(1)

    def time_expr(self, model: str) -> str:
        sm = self.models[model]
        name = sm["defaults"]["agg_time_dimension"]
        dim = next(d for d in sm["dimensions"] if d["name"] == name)
        return dim.get("expr", name)

    def measure_sql(self, name: str) -> str:
        _, measure = self.measures[name]
        expr = str(measure.get("expr", name))
        agg = measure["agg"]
        if measure.get("non_additive_dimension"):
            raise Unsupported(f"measure {name} is semi-additive")
        if agg == "sum":
            return f"sum({expr})"
        if agg == "count":
            return f"count({expr})"
        if agg == "count_distinct" and name in ADDITIVE_DISTINCT:
            return f"count(distinct {expr})"
        raise Unsupported(f"measure {name} ({agg}) is not additive across the export grain")


def metric_measure(metric: dict) -> str:
    measure = metric["type_params"]["measure"]
    return measure if isinstance(measure, str) else measure["name"]


# ----------------------------------------------------------------------- SQL generation
def render_sql(export: Export, layer: SemanticLayer) -> str:
    time_col = export.time_column
    ctes: list[str] = []
    branches: list[str] = []
    for source in export.sources:
        model = source.semantic_model
        missing = set(export.dims) - set(source.dims)
        if missing:
            raise ValueError(f"{export.name}: source {model} lacks dims {sorted(missing)}")
        own = [m for m in export.measures if layer.measures.get(m, ("",))[0] == model]
        time_expr = layer.time_expr(model)
        if export.grain == "month":
            time_expr = f"cast({{{{ dbt.date_trunc('month', '{time_expr}') }}}} as date)"
        keys = [time_expr] + [source.dims[d] for d in export.dims]
        select = [f"{time_expr} as {time_col}"]
        select += [expr if expr == d else f"{expr} as {d}" for d, expr in zip(export.dims, keys[1:])]
        select += [f"{layer.measure_sql(m)} as {col(m)}" for m in own]
        ctes.append(
            f"{model} as (\n    select\n"
            + ",\n".join(f"        {s}" for s in select)
            + f"\n    from {{{{ ref('{layer.ref_name(model)}') }}}}\n    group by\n"
            + ",\n".join(f"        {k}" for k in keys)
            + "\n)"
        )
        cols = [time_col, *export.dims] + [col(m) if m in own else f"0 as {col(m)}" for m in export.measures]
        branches.append("    select\n" + ",\n".join(f"        {c}" for c in cols) + f"\n    from {model}")

    for source_model in {s.semantic_model for s in export.sources}:
        layer.ref_name(source_model)  # validate early
    ctes.append("unioned as (\n" + "\n    union all\n".join(branches) + "\n)")

    group = [time_col, *export.dims]
    agg = [f"        coalesce(sum({col(m)}), 0) as {col(m)}" for m in export.measures]
    ctes.append(
        "aggregated as (\n    select\n"
        + ",\n".join([f"        {g}" for g in group] + agg)
        + "\n    from unioned\n    group by\n"
        + ",\n".join(f"        {g}" for g in group)
        + "\n)"
    )

    if export.lookups:
        joins, lookup_cols = [], []
        for lk in export.lookups:
            ctes.append(f"{lk.ref} as (\n    select * from {{{{ ref('{lk.ref}') }}}}\n)")
            joins.append(f"    left join {lk.ref} on aggregated.{lk.key} = {lk.ref}.{lk.key}")
            lookup_cols += [f"{lk.ref}.{c}" for c in lk.columns]
        cols = [f"aggregated.{c}" for c in group] + lookup_cols + [f"aggregated.{col(m)}" for m in export.measures]
        ctes.append(
            "final as (\n    select\n"
            + ",\n".join(f"        {c}" for c in cols)
            + "\n    from aggregated\n"
            + "\n".join(joins)
            + "\n)"
        )
        last = "final"
    else:
        last = "aggregated"

    grain = ", ".join([export.grain.replace("day", "business date"), *export.dims])
    header = f"-- {GENERATED}\n-- Grain: one row per {grain}.\n"
    return header + "with\n\n" + ",\n\n".join(ctes) + f"\n\nselect * from {last}\n"


# ------------------------------------------------------------- Lightdash translation
FILTER_RE = re.compile(r"\{\{\s*Dimension\('(\w+)__(\w+)'\)\s*\}\}")


class Translator:
    """Translates MetricFlow metrics into Lightdash metrics on one export table."""

    def __init__(self, export: Export, layer: SemanticLayer):
        self.export = export
        self.layer = layer
        self.out: dict[str, dict] = {}

    # -- public
    def add(self, name: str, visible: bool = True) -> None:
        self._register(name)
        if visible:
            self.out[name].pop("hidden", None)

    # -- helpers
    def _metric(self, name: str) -> dict:
        if name not in self.layer.metrics:
            raise Unsupported(f"unknown metric {name}")
        return self.layer.metrics[name]

    def _column(self, measure: str) -> str:
        if measure not in self.export.measures:
            raise Unsupported(f"measure {measure} is not in {self.export.name}")
        return f"${{TABLE}}.{col(measure)}"

    def _filter_sql(self, flt: str) -> str:
        def repl(match: re.Match) -> str:
            col = match.group(2)
            if col not in self.export.columns:
                raise Unsupported(f"filter column {col} is not in {self.export.name}")
            return f"${{TABLE}}.{col}"

        sql = FILTER_RE.sub(repl, flt)
        if "{{" in sql:
            raise Unsupported(f"unsupported filter: {flt}")
        return sql.strip()

    def _describe(self, metric: dict) -> dict:
        name = metric["name"]
        entry: dict = {"label": metric.get("label", name)}
        desc = " ".join(str(metric.get("description", "")).split())
        entry["description"] = (desc + " " if desc else "") + f"(MetricFlow metric `{name}`.)"
        if name.endswith(("_pct", "_rate")):
            entry.update(format="percent", round=1)
        elif "AED" in entry["label"] or metric["type"] in ("ratio", "derived"):
            entry["round"] = 2
        else:
            entry["round"] = 0
        return entry

    def _register(self, name: str) -> str:
        if name in self.out:
            return f"${{{name}}}"
        metric = self._metric(name)
        kind = metric["type"]
        if kind == "simple":
            measure = metric_measure(metric)
            self.layer.measure_sql(measure)  # raises if not additive
            body = {"type": "sum", "sql": self._column(measure)}
        elif kind == "derived":
            body = {"type": "number", "sql": self._derived(metric, None)}
        elif kind == "ratio":
            body = {"type": "number", "sql": self._ratio(metric, None)}
        else:
            raise Unsupported(f"{kind} metrics have no pre-aggregated equivalent")
        self.out[name] = {**body, **self._describe(metric), "hidden": True}
        return f"${{{name}}}"

    def _input(self, name: str, flt: str | None) -> str:
        """SQL for one input of a derived/ratio metric, optionally under a filter."""
        if flt is None:
            return self._register(name)
        metric = self._metric(name)
        kind = metric["type"]
        if kind == "simple":
            measure = metric_measure(metric)
            cond = self._filter_sql(flt)
            slug = re.sub(r"\W+", "_", cond.replace("${TABLE}.", "")).strip("_")
            helper = f"{name}__{slug}"
            if helper not in self.out:
                self.out[helper] = {
                    "type": "sum",
                    "sql": f"case when {cond} then {self._column(measure)} end",
                    "label": f"{metric.get('label', name)} where {slug}",
                    "description": f"Helper: MetricFlow metric `{name}` filtered on {flt.strip()}.",
                    "hidden": True,
                    "round": 2,
                }
            return f"${{{helper}}}"
        if kind == "derived":
            return f"({self._derived(metric, flt)})"
        if kind == "ratio":
            return f"({self._ratio(metric, flt)})"
        raise Unsupported(f"{kind} metric {name} cannot be filtered here")

    @staticmethod
    def _combine(outer: str | None, inner: str | None) -> str | None:
        if outer and inner:
            raise Unsupported("nested metric filters are not translated")
        return outer or inner

    def _derived(self, metric: dict, flt: str | None) -> str:
        subs: dict[str, str] = {}
        for item in metric["type_params"]["metrics"]:
            item = {"name": item} if isinstance(item, str) else item
            key = item.get("alias", item["name"])
            subs[key] = self._input(item["name"], self._combine(flt, item.get("filter")))
        pattern = re.compile(r"\b(" + "|".join(map(re.escape, sorted(subs, key=len, reverse=True))) + r")\b")
        return pattern.sub(lambda m: subs[m.group(1)], " ".join(metric["type_params"]["expr"].split()))

    def _ratio(self, metric: dict, flt: str | None) -> str:
        parts = []
        for side in ("numerator", "denominator"):
            item = metric["type_params"][side]
            item = {"name": item} if isinstance(item, str) else item
            parts.append(self._input(item["name"], self._combine(flt, item.get("filter"))))
        return f"{parts[0]} / nullif({parts[1]}, 0)"


def translate(export: Export, layer: SemanticLayer) -> tuple[dict[str, dict], dict[str, str]]:
    """Lightdash metrics for an export, plus {metric: reason} for those that do not fit."""
    tr = Translator(export, layer)
    skipped: dict[str, str] = {}
    wanted = export.metrics if export.metrics is not None else tuple(layer.metrics)
    for name in wanted:
        snapshot = dict(tr.out)
        try:
            tr.add(name)
        except Unsupported as exc:
            if export.metrics is not None:
                raise
            tr.out = snapshot  # drop anything half-registered
            skipped[name] = str(exc)
    return tr.out, skipped


def expand_sql(metrics: dict[str, dict], name: str, table: str) -> str:
    """Plain SQL for a Lightdash metric over `table` (used by the reconciliation)."""
    entry = metrics[name]
    sql = entry["sql"].replace("${TABLE}", table)
    if entry["type"] == "sum":
        return f"sum({sql})"
    return re.sub(r"\$\{(\w+)\}", lambda m: f"({expand_sql(metrics, m.group(1), table)})", sql)


# -------------------------------------------------------------------- YAML + catalog
def render_yaml(layer: SemanticLayer) -> str:
    models = []
    for export in EXPORTS:
        metrics, _ = translate(export, layer)
        meta: dict = {}
        if export.joins:
            meta["joins"] = [
                {"join": model, "sql_on": f"${{{export.name}.{local}}} = ${{{model}.{remote}}}"}
                for model, local, remote in export.joins
            ]
        meta["metrics"] = metrics
        columns: list[dict] = [{
            "name": export.time_column,
            "description": "Business date (day grain)" if export.grain == "day" else "First day of the month",
            "data_tests": ["not_null"],
        }]
        columns += [{"name": d, "data_tests": ["not_null"]} for d in export.dims]
        columns += [{"name": c} for lk in export.lookups for c in lk.columns]
        for measure in export.measures:
            model, spec = layer.measures[measure]
            desc = spec.get("description") or f"MetricFlow measure `{measure}` from {model}"
            columns.append({
                "name": col(measure),
                "description": f"{desc}: {spec['agg']}({spec.get('expr', measure)})",
                "config": {"meta": {"dimension": {"hidden": True}}},
            })
        models.append({
            "name": export.name,
            "description": export.description,
            "config": {"meta": meta},
            "data_tests": [{
                "dbt_utils.unique_combination_of_columns": {
                    "arguments": {"combination_of_columns": [export.time_column, *export.dims]},
                },
            }],
            "columns": columns,
        })
    body = yaml.safe_dump({"version": 2, "models": models}, sort_keys=False, width=110, allow_unicode=True)
    return f"# {GENERATED}\n\n" + body


def render_catalog(layer: SemanticLayer) -> str:
    where: dict[str, list[str]] = {}
    reasons: dict[str, str] = {}
    for export in EXPORTS:
        metrics, skipped = translate(export, layer)
        for name, entry in metrics.items():
            if not entry.get("hidden"):
                where.setdefault(name, []).append(export.name)
        for name, reason in skipped.items():
            reasons.setdefault(name, reason)

    lines = [
        "# Metrics catalog",
        "",
        f"<!-- {GENERATED} -->",
        "",
        "MetricFlow (`dbt/models/semantic/`) is the single source of truth. Metrics marked with a",
        "Lightdash explore were translated onto a pre-aggregated table by `scripts/semantic_export.py`",
        "and reconciled against `mf query` by `scripts/reconcile_metrics.py`. The rest are served by",
        "MetricFlow only, for the reason given.",
        "",
        "| Metric | Label | Type | Lightdash explore |",
        "| --- | --- | --- | --- |",
    ]
    for name, metric in layer.metrics.items():
        if name in where:
            avail = ", ".join(f"`{e}`" for e in where[name])
        else:
            avail = f"MetricFlow only: {reasons.get(name, 'not exported')}"
        lines.append(f"| `{name}` | {metric.get('label', name)} | {metric['type']} | {avail} |")
    return "\n".join(lines) + "\n"


def outputs() -> dict[Path, str]:
    layer = SemanticLayer.load()
    files = {OUT_DIR / f"{e.name}.sql": render_sql(e, layer) for e in EXPORTS}
    files[OUT_DIR / "_metrics__models.yml"] = render_yaml(layer)
    files[CATALOG] = render_catalog(layer)
    return files


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = parser.parse_args()

    stale = []
    for path, content in outputs().items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == content:
            continue
        if args.check:
            stale.append(path.relative_to(ROOT).as_posix())
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
            print(f"wrote {path.relative_to(ROOT).as_posix()}")
    if stale:
        print("Generated files are out of date; run python scripts/semantic_export.py:")
        print("\n".join(f"  {p}" for p in stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
