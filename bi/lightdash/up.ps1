# Start the local Lightdash stack. On first run:
#   1. writes bi/lightdash/.env with random secrets (git-ignored)
#   2. registers the admin user and organization through the API
#   3. creates a personal access token for the CLI and stores it in .env
$ErrorActionPreference = 'Stop'
$here = $PSScriptRoot
$envFile = Join-Path $here '.env'
$url = 'http://127.0.0.1:8080'

function New-Secret([int]$bytes = 24) {
    $buf = New-Object byte[] $bytes
    [Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($buf)
    -join ($buf | ForEach-Object { $_.ToString('x2') })
}

function Read-DotEnv {
    $d = @{}
    Get-Content $envFile | Where-Object { $_ -match '^\s*([^#=]+)=(.*)$' } | ForEach-Object { $d[$Matches[1].Trim()] = $Matches[2].Trim() }
    $d
}

if (-not (Test-Path $envFile)) {
    @(
        "LIGHTDASH_SECRET=$(New-Secret 32)"
        "PGPASSWORD=$(New-Secret)"
        "MINIO_ROOT_USER=najm"
        "MINIO_ROOT_PASSWORD=$(New-Secret)"
        "LD_ADMIN_EMAIL=admin@najm.local"
        "LD_ADMIN_PASSWORD=Najm-$(New-Secret 9)"
    ) | Set-Content -Encoding ascii $envFile
    Write-Host "Created $envFile (keep it: LIGHTDASH_SECRET encrypts stored warehouse credentials)"
}

# docker writes progress to stderr; judge success by its exit code, not by stderr output
$ErrorActionPreference = 'Continue'
docker compose -f (Join-Path $here 'docker-compose.yml') --env-file $envFile up --detach --remove-orphans 2>&1 |
    ForEach-Object { "$_" }
if ($LASTEXITCODE -ne 0) { throw "docker compose up failed ($LASTEXITCODE)" }
$ErrorActionPreference = 'Stop'

Write-Host 'Waiting for Lightdash (first start runs ~1,000 database migrations: 15-25 minutes)...'
$deadline = (Get-Date).AddMinutes(30)
while ($true) {
    try { if ((Invoke-WebRequest "$url/api/v1/health" -UseBasicParsing -TimeoutSec 5).StatusCode -eq 200) { break } } catch {}
    if ((Get-Date) -gt $deadline) { throw 'Lightdash did not become healthy within 30 minutes; see docker logs najm-lightdash-lightdash-1' }
    Start-Sleep -Seconds 5
}

$cfg = Read-DotEnv
if (-not $cfg['LD_ADMIN_API_KEY']) {
    $health = Invoke-RestMethod "$url/api/v1/health"
    $session = New-Object Microsoft.PowerShell.Commands.WebRequestSession
    $json = @{ 'Content-Type' = 'application/json' }
    if ($health.results.requiresOrgRegistration) {
        $user = @{ firstName = 'Najm'; lastName = 'Admin'; email = $cfg['LD_ADMIN_EMAIL']; password = $cfg['LD_ADMIN_PASSWORD'] }
        Invoke-RestMethod "$url/api/v1/user" -Method Post -Headers $json -Body ($user | ConvertTo-Json) -WebSession $session | Out-Null
        Invoke-RestMethod "$url/api/v1/org" -Method Put -Headers $json -WebSession $session `
            -Body (@{ name = 'Najm Retail' } | ConvertTo-Json) | Out-Null
        Write-Host "Registered admin $($cfg['LD_ADMIN_EMAIL']) and organization 'Najm Retail'"
    } else {
        $login = @{ email = $cfg['LD_ADMIN_EMAIL']; password = $cfg['LD_ADMIN_PASSWORD'] }
        Invoke-RestMethod "$url/api/v1/login" -Method Post -Headers $json -Body ($login | ConvertTo-Json) -WebSession $session | Out-Null
    }
    $tokenReq = @{ description = 'CLI deploys (bi/lightdash/deploy.ps1)'; autoGenerated = $false; expiresAt = $null }
    $token = Invoke-RestMethod "$url/api/v1/user/me/personal-access-tokens" -Method Post -Headers $json `
        -Body ($tokenReq | ConvertTo-Json) -WebSession $session
    Add-Content -Encoding ascii $envFile "LD_ADMIN_API_KEY=$($token.results.token)"
    Write-Host 'Created a CLI access token (stored in .env)'
}

Write-Host "Lightdash: http://localhost:8080  (login: LD_ADMIN_EMAIL / LD_ADMIN_PASSWORD in bi/lightdash/.env)"
